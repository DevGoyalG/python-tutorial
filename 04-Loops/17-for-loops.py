# For Loops in Python #

name = "Abhishek"
for i in name:
    print(i)

name = "Abhishek"
for i in name:
    print(i)
    if(i == "b"):
        print("This is something special!")

colors = ["Red", "Green", "Blue", "Yellow"]
for color in colors:
    print(color)

colors = ["Red", "Green", "Blue", "Yellow"]
for color in colors:
    print(color)
    for i in color:
        print(i)

for x in range(5):  # print value from 0 to 4
    print(x)

for x in range(5):
    print(x+1)

for x in range (1,9):
    print(x)

for x in range (1,9):
    print(x+1)

for x in range (1,2000):
    print(x)

for x in range (1,12,2):
    print(x)